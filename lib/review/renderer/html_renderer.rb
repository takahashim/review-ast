      def visit_headline(node)
        level = node.level
        caption = render_caption_inline(node.caption_node)

        if node.nonum? || node.notoc? || node.nodisp?
          # Use label if provided, otherwise use auto_id generated by Compiler
          id = normalize_id(node.label || node.auto_id)

          spacing_before = level > 1 ? "\n" : ''

          if node.nodisp?
            a_tag = %Q(<a id="#{id}" />)
            %Q(#{spacing_before}#{a_tag}<h#{level} id="#{id}" hidden="true">#{caption}</h#{level}>\n)
          elsif node.notoc?
            %Q(#{spacing_before}<h#{level} id="#{id}" notoc="true">#{caption}</h#{level}>\n)
          else
            %Q(#{spacing_before}<h#{level} id="#{id}">#{caption}</h#{level}>\n)
          end
        else
          prefix, anchor = headline_prefix(level)

          anchor_html = anchor ? %Q(<a id="h#{anchor}"></a>) : ''
          secno_html = prefix ? %Q(<span class="secno">#{prefix}</span>) : ''
          spacing_before = level > 1 ? "\n" : ''

          if node.label
            label_id = normalize_id(node.label)
            %Q(#{spacing_before}<h#{level} id="#{label_id}">#{anchor_html}#{secno_html}#{caption}</h#{level}>\n)
          else
            "#{spacing_before}<h#{level}>#{anchor_html}#{secno_html}#{caption}</h#{level}>\n"
          end
        end
      end

      def visit_paragraph(node)
        # render_source_lines: a newline @<raw> writes stays, as in HTMLBuilder.
        content = render_source_lines(node.children).strip

        # Check for noindent attribute
        if node.noindent?
          %Q(<p class="noindent">#{content}</p>\n)
        else
          "<p>#{content}</p>\n"
        end
      end

      # Join paragraph lines according to join_lines_by_lang setting
      # This matches HTMLBuilder's join_lines_to_paragraph behavior
      #
      # @param content [String] paragraph content with newlines
      # @return [String] processed content with lines joined appropriately
      def join_paragraph_lines(content)
        if config['join_lines_by_lang']
          # Split by newlines to get individual lines
          lines = content.split("\n")

          # Add spaces between lines based on language rules
          lazy = true
          lang = config['language'] || 'ja'
          0.upto(lines.size - 2) do |n|
            if add_space?(lines[n], lines[n + 1], lang, lazy)
              lines[n] += ' '
            end
          end
          lines.join
        else
          # Default: just remove newlines (no space added)
          content.gsub(/\n+/, '')
        end
      end

      def render_list_item_inline(item)
        return render_children(item) unless config['join_lines_by_lang']

        breaks = item.source_line_breaks
        parts = []
        inline = +''
        item.children.each_with_index do |child, index|
          if inline_content_node?(child)
            inline << "\n" if !inline.empty? && breaks.include?(index)
            inline << visit(child)
          else
            # A nested block (a sub-list) keeps its own line structure.
            parts << join_paragraph_lines(inline) << visit(child)
            inline = +''
          end
        end
        parts << join_paragraph_lines(inline)
        parts.join
      end

      def visit_list(node)
        tag = case node.list_type
              when :ul
                'ul'
              when :ol
                'ol'
              when :dl
                'dl'
              else
                raise NotImplementedError, "HTMLRenderer does not support list_type #{node.list_type}."
              end

        # Check for start_number for ordered lists
        # Only output start attribute if it's not the default value (1)
        start_attr = ''
        if node.list_type == :ol && node.start_number && node.start_number != 1
          start_attr = %Q( start="#{node.start_number}")
        end

        content = render_children(node)
        # Format list items with proper line breaks like HTMLBuilder
        formatted_content = content.gsub(%r{</li>(?=<li>)}, "</li>\n")
        formatted_content = formatted_content.gsub(/<li>([^<]*)<ul>/, "<li>\\1<ul>\n")
        formatted_content = formatted_content.gsub('</ul></li>', "</ul>\n</li>")
        "<#{tag}#{start_attr}>\n#{formatted_content}\n</#{tag}>\n"
      end

      def visit_list_item(node)
        # Get parent list to determine list type
        parent_list = node.parent
        if parent_list && parent_list.list_type == :dl
          # Definition list item - use term_children for term like LaTeXRenderer
          term = if node.term_children&.any?
                   node.term_children.map { |child| visit(child) }.join
                 else
                   ''
                 end

          # Children contain the definition content
          # Join all children into a single dd like HTMLBuilder does with join_lines_to_paragraph
          if node.children.empty?
            # Only term, no definition - add empty dd like HTMLBuilder
            "<dt>#{term}</dt><dd></dd>"
          else
            # Render all child content and join together
            definition_parts = node.children.map { |child| visit(child) }
            # Join multiple paragraphs/text into single dd content, removing <p> tags
            definition_content = definition_parts.map { |part| part.gsub(%r{</?p[^>]*>}, '').strip }.join
            "<dt>#{term}</dt><dd>#{definition_content}</dd>"
          end
        else
          # Regular list item. HTMLBuilder#ul_item joins the item's source
          # lines with join_lines_to_paragraph: plain concatenation, or the
          # language-aware space with join_lines_by_lang. Continuation lines are
          # separate children, marked by source_line_breaks.
          "<li>#{render_list_item_inline(node)}</li>"
        end
      end

      def visit_text(node)
