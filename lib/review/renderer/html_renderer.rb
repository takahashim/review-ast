      def visit_column(node)
        # Use auto_id generated by Compiler for anchor
        id_attr = node.label ? %Q( id="#{normalize_id(node.label)}") : ''
        anchor_id = %Q(<a id="#{node.auto_id}"></a>)

        # HTMLBuilder#column_begin uses <h{level}> where level is the column
        # heading's level (the number of '=' signs), not a fixed h4.
        level = node.level
        caption_content = render_caption_inline(node.caption_node)
        caption_html = if caption_content.empty?
                         node.label ? anchor_id : ''
                       elsif node.label
                         %Q(<h#{level}#{id_attr}>#{anchor_id}#{caption_content}</h#{level}>)
                       else
                         %Q(<h#{level}>#{anchor_id}#{caption_content}</h#{level}>)
                       end

        content = render_children(node)

        %Q(<div class="column">\n#{caption_html}#{content}</div>)
      end

      def visit_minicolumn(node)
        type = node.minicolumn_type.to_s
        id_attr = node.id ? %Q( id="#{normalize_id(node.id)}") : ''

        caption_content = render_caption_inline(node.caption_node)
        caption_html = caption_content.empty? ? '' : %Q(<p class="caption">#{caption_content}</p>\n)

        # Content already contains proper paragraph structure from ParagraphNode children
        content_html = render_children(node)

        %Q(<div class="#{type}"#{id_attr}>\n#{caption_html}#{content_html}</div>\n)
      end

      def visit_image(node)
        id_attr = node.id ? %Q( id="#{normalize_id(node.id)}") : ''

        caption_node = node.caption_node

        # Process image with caption context management. The image helpers fall
        # back to the dummy image when node.image_path is nil (unbound), resolved
        # at compile time, so no chapter image index lookup is needed here.
        if caption_node
          @rendering_context.with_child_context(:caption) do |caption_context|
            image_image_html_with_context(node, id_attr, caption_context)
          end
        else
          image_image_html(node, id_attr)
        end
      end

