# Generates lib/review/ast/command_table_snapshot.rb: what Re:VIEW's builders
# implement, read once here so that review-ast does not have to ask the
# builders at run time (doc/design-extension-api.ja.md, section 2).
#
# The snapshot records, for the installed review gem:
#
# - every block command and inline op Re:VIEW itself declares
#   (ReVIEW::Compiler::SYNTAX / INLINE), with the builders that implement it
#   -- the "builder does not support command" rule of ReVIEW::Compiler;
# - for each builder, the methods Re:VIEW defines on it, which tells a
#   review-ext.rb redefinition the AST does not call from a helper of the
#   book's own.
#
# It has to run in a process that has loaded nothing but the review gem: a
# review-ext.rb, or a test that reopens a builder, would change what it
# reads. test/ast/test_command_table.rb runs it in a child process and
# compares the output with the committed file.
#
# Usage:
#   ruby tools/generate_command_table.rb            # write the snapshot
#   ruby tools/generate_command_table.rb --stdout   # print instead of writing

require 'review/compiler'
require 'review/version'
require 'review/htmlbuilder'
require 'review/latexbuilder'
require 'review/idgxmlbuilder'
require 'review/plaintextbuilder'
require 'review/topbuilder'

module ReVIEW
  module AST
    # Writes the builder snapshot CommandTable reads.
    class CommandTableGenerator
      SNAPSHOT_PATH = File.expand_path('../lib/review/ast/command_table_snapshot.rb', __dir__)

      # The builders the AST renderers stand in for (Renderer::Base#legacy_builder_class).
      BUILDERS = %w[HTMLBuilder LATEXBuilder IDGXMLBuilder PLAINTEXTBuilder TOPBuilder].freeze

      # Where the review gem's sources live: a method defined there is Re:VIEW's.
      REVIEW_DIR = File.join(File.expand_path('../..', ReVIEW::Compiler.instance_method(:compile).source_location.first), '')

      WIDTH = 100

      def blocks
        ReVIEW::Compiler::SYNTAX.keys.sort.to_h do |name|
          [name, BUILDERS.select { |builder| builder_class(builder).public_method_defined?(name) }]
        end
      end

      def inlines
        ReVIEW::Compiler::INLINE.keys.sort.to_h do |name|
          [name, BUILDERS.select { |builder| builder_class(builder).public_method_defined?(:"inline_#{name}") }]
        end
      end

      # Public and private, as a review-ext.rb can redefine either.
      def builder_methods
        BUILDERS.to_h do |builder|
          klass = builder_class(builder)
          names = (klass.instance_methods + klass.private_instance_methods).uniq.select { |name| review_method?(klass, name) }
          [builder, names.sort]
        end
      end

      def source
        <<~RUBY
          # frozen_string_literal: true

          # Generated by tools/generate_command_table.rb from review #{ReVIEW::VERSION}. Do not edit;
          # regenerate instead (test/ast/test_command_table.rb checks it).

          module ReVIEW
            module AST
              class CommandTable
                # The review gem this snapshot was read from.
                SNAPSHOT_REVIEW_VERSION = '#{ReVIEW::VERSION}'

                # Block commands Re:VIEW declares, with the builders that implement them.
                BUILTIN_BLOCKS = {
          #{support_entries(blocks)}
                }.freeze

                # Inline ops Re:VIEW declares, with the builders that implement them.
                BUILTIN_INLINES = {
          #{support_entries(inlines)}
                }.freeze

                # The methods Re:VIEW defines on each builder (public and private).
                BUILDER_METHODS = {
          #{method_entries}
                }.freeze
              end
            end
          end
        RUBY
      end

      def write
        File.write(SNAPSHOT_PATH, source)
      end

      private

      def builder_class(name)
        ReVIEW.const_get(name)
      end

      def review_method?(klass, name)
        method = klass.instance_method(name)
        file = method.source_location&.first
        method.owner.name&.start_with?('ReVIEW::') && !file.nil? && file.start_with?(REVIEW_DIR)
      end

      def support_entries(table)
        table.map do |name, builders|
          "        #{name}: %w[#{builders.join(' ')}].freeze"
        end.join(",\n")
      end

      def method_entries
        builder_methods.map do |builder, names|
          lines = wrap(names.map(&:to_s), indent: 10)
          "        '#{builder}' => %i[\n#{lines}\n        ].freeze"
        end.join(",\n")
      end

      def wrap(words, indent:)
        lines = [+'']
        words.each do |word|
          lines << +'' if !lines.last.empty? && indent + lines.last.size + 1 + word.size > WIDTH
          lines.last << ' ' unless lines.last.empty?
          lines.last << word
        end
        lines.map { |line| (' ' * indent) + line }.join("\n")
      end
    end
  end
end

if $PROGRAM_NAME == __FILE__
  generator = ReVIEW::AST::CommandTableGenerator.new
  if ARGV.include?('--stdout')
    print generator.source
  else
    generator.write
    puts "wrote #{ReVIEW::AST::CommandTableGenerator::SNAPSHOT_PATH}"
  end
end
