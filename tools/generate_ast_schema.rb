# Generates the JSON Schema for the serialized AST by introspecting real dumps.
#
# The schema is derived, not hand-written: it is built from what the serializers
# actually emit over the sample corpora, so it cannot drift from them by being
# forgotten. design-improvements #4 recorded this as the way to produce a schema
# when one is needed -- introspect real dumps rather than first introducing a
# field-declaration DSL, since the irregular serializations (TableNode's
# header/body rows, ReferenceNode's resolved_data, conditional keys) resist a
# naive DSL.
#
# Usage:
#   ruby tools/generate_ast_schema.rb            # write schema/ast-format-1.schema.json
#   ruby tools/generate_ast_schema.rb --stdout   # print instead of writing

require 'json'
require 'set'
require 'stringio'
require 'yaml'
require_relative '../lib/review/ast/compiler'
require_relative '../lib/review/ast/json_serializer'
require 'review/book'
require 'review/configure'
require 'review/i18n'

module ReVIEW
  module AST
    # Builds a JSON Schema from serialized trees.
    class SchemaGenerator
      SCHEMA_PATH = File.expand_path('../schema/ast-format-1.schema.json', __dir__)

      # Keys every node carries, described once and referenced by each node type.
      COMMON_DESCRIPTIONS = {
        'type' => 'Node class name, without the module prefix.',
        'location' => 'Source position the node was parsed from.',
        'children' => 'Child nodes. Absent on leaf nodes.'
      }.freeze

      def initialize
        @properties = Hash.new { |hash, key| hash[key] = {} }
        @seen_types = Set.new
        # ResolvedData carries a "type" like a node does, but it is not one: it
        # only ever appears under a ReferenceNode's resolved_data. Keeping the
        # two apart stops the schema from allowing an ImageReference wherever a
        # node is expected.
        @resolved_data_types = Set.new
      end

      # @param root [Node] A compiled tree to learn from
      def observe(root)
        walk(JSON.parse(JSONSerializer.serialize(root)))
      end

      # @return [Hash] The schema document
      def schema
        {
          '$schema' => 'https://json-schema.org/draft/2020-12/schema',
          '$id' => 'https://github.com/kmuto/review/schema/ast-format-1.schema.json',
          'title' => 'Re:VIEW serialized AST (ast_format 1)',
          'description' => 'Generated by tools/generate_ast_schema.rb; do not edit by hand. ' \
                           'See doc/ast-format.ja.md for the compatibility policy.',
          'type' => 'object',
          'required' => %w[ast_format generator root],
          'additionalProperties' => false,
          'properties' => {
            'ast_format' => { 'const' => JSONSerializer::AST_FORMAT_VERSION },
            'generator' => { 'type' => 'string', 'description' => 'Informational. Readers must not branch on it.' },
            'root' => { '$ref' => '#/$defs/node' }
          },
          '$defs' => definitions
        }
      end

      # @return [Array<String>] Node type names the schema covers
      def covered_types
        (@seen_types - @resolved_data_types).to_a.sort
      end

      # @return [Array<String>] ResolvedData type names the schema covers
      def resolved_data_types
        @resolved_data_types.to_a.sort
      end

      private

      def definitions
        defs = {
          'node' => {
            'description' => 'Any AST node, discriminated by "type".',
            'oneOf' => covered_types.map { |type| { '$ref' => "#/$defs/#{type}" } }
          },
          'resolved_data' => {
            'description' => 'Resolved cross-reference data, discriminated by "type".',
            'oneOf' => resolved_data_types.map { |type| { '$ref' => "#/$defs/#{type}" } }
          },
          'location' => {
            'type' => %w[object null],
            'additionalProperties' => false,
            'properties' => {
              'filename' => { 'type' => %w[string null] },
              'lineno' => { 'type' => %w[integer null] },
              'column' => { 'type' => %w[integer null] }
            }
          }
        }
        (covered_types + resolved_data_types).each { |type| defs[type] = node_definition(type) }
        defs
      end

      def node_definition(type)
        properties = @properties[type].keys.sort.to_h do |key|
          [key, property_schema(type, key)]
        end

        {
          'type' => 'object',
          # Closed on purpose: a key the schema does not know about means the
          # serializer changed and the schema was not regenerated.
          'additionalProperties' => false,
          'required' => ['type'],
          'properties' => properties
        }
      end

      def property_schema(type, key)
        observed = @properties[type][key]
        schema =
          case key
          when 'type' then { 'const' => type }
          when 'location' then { '$ref' => '#/$defs/location' }
          when 'resolved_data' then { '$ref' => '#/$defs/resolved_data' }
          else json_types_to_schema(observed)
          end
        description = COMMON_DESCRIPTIONS[key]
        description ? schema.merge('description' => description) : schema
      end

      # Turn the set of observed JSON types into a schema fragment. Node-valued
      # keys (children, caption_node, table rows, ...) are referenced rather
      # than described inline.
      def json_types_to_schema(observed)
        return { '$ref' => '#/$defs/node' } if observed == Set['node']
        return { 'type' => 'array', 'items' => { '$ref' => '#/$defs/node' } } if observed == Set['node_array']

        types = observed.to_a.sort
        types.size == 1 ? { 'type' => types.first } : { 'type' => types }
      end

      def walk(hash)
        type = hash['type']
        return unless type.is_a?(String)

        @seen_types << type
        hash.each do |key, value|
          @resolved_data_types << value['type'] if key == 'resolved_data' && node?(value)
          @properties[type][key] ||= Set.new
          # An empty children array is still a node array (an empty paragraph:
          # a blank line inside a definition), not an untyped one.
          @properties[type][key] << (key == 'children' && value == [] ? 'node_array' : json_type_of(value))
          descend(value)
        end
      end

      def descend(value)
        case value
        when Hash then walk(value)
        when Array then value.each { |item| descend(item) }
        end
      end

      def json_type_of(value)
        case value
        when nil then 'null'
        when true, false then 'boolean'
        when Integer then 'integer'
        when Float then 'number'
        when String then 'string'
        when Array then value.all? { |item| node?(item) } && !value.empty? ? 'node_array' : 'array'
        when Hash then node?(value) ? 'node' : 'object'
        end
      end

      def node?(value)
        value.is_a?(Hash) && value['type'].is_a?(String)
      end
    end
  end
end

# Sources the generator learns from. Between them these reach every node type a
# document can produce; test/ast/test_ast_schema.rb fails if one is missed.
module ReVIEW
  module AST
    module SchemaSources
      CORPORA = [
        File.expand_path('../samples/syntax-book', __dir__),
        File.expand_path('../samples/md-syntax-book', __dir__)
      ].freeze

      module_function

      # @yield [Node] each compiled chapter tree
      def each_tree(&block)
        CORPORA.each do |dir|
          next unless File.directory?(dir)

          Dir.chdir(dir) do
            config = ReVIEW::Configure.values
            loaded = YAML.safe_load_file('config.yml', permitted_classes: [Date, Time, Symbol])
            config.merge!(loaded) if loaded
            book = ReVIEW::Book::Base.new('.', config: config)
            book.generate_indexes
            ReVIEW::I18n.setup(config['language'] || 'ja')

            book.chapters.each do |chapter|
              yield(ReVIEW::AST::Compiler.for_chapter(chapter).compile_to_ast(chapter))
            rescue StandardError
              next
            end
          end
        end
        synthetic_trees.each(&block)
      end

      # Nodes no corpus can produce without changing the process it runs in:
      # an ExtensionBlockNode needs a review-ext.rb, which reopens classes for
      # good, so it is built directly -- once with a body, once without.
      def synthetic_trees
        require_relative('../lib/review/ast/extension_block_node')
        location = ReVIEW::AST::SourceLocation.new('ext.re', 1, 1)
        document = ReVIEW::AST::DocumentNode.new(location: location)
        document.add_child(ReVIEW::AST::ExtensionBlockNode.new(location: location, block_type: :mybox, args: ['caption'], lines: ['body']))
        document.add_child(ReVIEW::AST::ExtensionBlockNode.new(location: location, block_type: :mymark, args: ['id']))
        [document]
      end
    end
  end
end

if $PROGRAM_NAME == __FILE__
  ReVIEW.logger = ReVIEW::Logger.new(StringIO.new)
  generator = ReVIEW::AST::SchemaGenerator.new
  ReVIEW::AST::SchemaSources.each_tree { |tree| generator.observe(tree) }

  json = "#{JSON.pretty_generate(generator.schema)}\n"
  if ARGV.include?('--stdout')
    puts json
  else
    path = ReVIEW::AST::SchemaGenerator::SCHEMA_PATH
    FileUtils.mkdir_p(File.dirname(path)) if defined?(FileUtils)
    require 'fileutils'
    FileUtils.mkdir_p(File.dirname(path))
    File.write(path, json)
    warn "wrote #{path} (#{generator.covered_types.size} node types)"
  end
end
